def get_seasonal_factor(item_name: str, month: int = None) -> float:
    """
    获取指定商品在指定月份的季节性价格系数。

    Args:
        item_name: 商品名称（如"鸡蛋"、"青菜"、"猪肉"）
        month: 月份（1-12），默认为当前月份

    Returns:
        价格系数（1.0 = 均价，>1 贵，<1 便宜）
    """
    if month is None:
        month = datetime.now().month

    # 精确匹配
    if item_name in _SEASONAL_FACTORS:
        return _SEASONAL_FACTORS[item_name][month - 1]

    # 模糊匹配（子串匹配）
    for cat, factors in _SEASONAL_FACTORS.items():
        if cat in item_name or item_name in cat:
            return factors[month - 1]

    # 默认大类
    for cat, factors in _SEASONAL_FACTORS.items():
        if len(cat) <= 3:  # 大类（蔬菜、水果、肉类等）
            if cat in item_name:
                return factors[month - 1]

    return 1.0  # 无匹配，返回默认


def get_season_context(month: int = None) -> str:
    """
    获取当前月份的季节描述文本，用于 LLM prompt。

    Returns:
        季节描述 + 时令商品提示 + 免责声明
    """
    if month is None:
        month = datetime.now().month

    desc = _SEASON_DESCRIPTIONS.get(month, "")
    lines = [f"当前月份：{month}月。{desc}"]

    # 时令商品提示
    cheap_items = []
    expensive_items = []
    for item, factors in _SEASONAL_FACTORS.items():
        factor = factors[month - 1]
        if len(item) <= 2:  # 跳过大类
            continue
        if factor < 0.85:
            cheap_items.append(f"{item}(系数{factor:.2f})")
        elif factor > 1.3:
            expensive_items.append(f"{item}(系数{factor:.2f})")

    if cheap_items:
        lines.append(f"当前时令/便宜商品：{'、'.join(cheap_items[:8])}")
    if expensive_items:
        lines.append(f"当前反季/偏贵商品：{'、'.join(expensive_items[:8])}")

    lines.append(_SEASONAL_DISCLAIMER)
    return "\n".join(lines)


def get_price_range(
    base_price: float, item_name: str, month: int = None, uncertainty: float = 0.15
) -> Tuple[float, float]:
    """
    根据基础价格和季节性系数，计算价格波动区间。

    Args:
        base_price: 基础均价
        item_name: 商品名称
        month: 月份
        uncertainty: 不确定性系数（默认 15%）

    Returns:
        (最低价, 最高价)
    """
    factor = get_seasonal_factor(item_name, month)
    adjusted = base_price * factor
    low = round(adjusted * (1 - uncertainty), 2)
    high = round(adjusted * (1 + uncertainty), 2)
    return (low, high)


def get_seasonal_prompt_snippet() -> str:
    """
    获取用于 LLM prompt 的季节性价格提示片段。
    """
    return get_season_context()